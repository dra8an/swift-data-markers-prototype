"""Generates the baked data of the 4 date name markers from CLDR JSON, one Swift file for each marker.

Usage:
  python3 -I generate.py --cldr <CLDR json full folder> --out <folder> [--markers A,B] [--locales ko,en | all] [--attributes 5,5s]

It also writes markers.json (marker name, hash, tag) and stats.json (sizes) into the output folder.
"""
import argparse
import json
import os

CLDR_VERSION = "49.0.0-BETA4"
TAG = b"dmk1"

# name: (CLDR package, calendar file and key, the field in the calendar, the order of the names)
MARKERS = {
    "MonthNamesGregorianV1": ("cldr-dates-full", "gregorian", "months", [str(i) for i in range(1, 13)]),
    "MonthNamesJapaneseV1": ("cldr-cal-japanese-full", "japanese", "months", [str(i) for i in range(1, 13)]),
    "WeekdayNamesGregorianV1": ("cldr-dates-full", "gregorian", "days", ["sun", "mon", "tue", "wed", "thu", "fri", "sat"]),
    "WeekdayNamesJapaneseV1": ("cldr-cal-japanese-full", "japanese", "days", ["sun", "mon", "tue", "wed", "thu", "fri", "sat"]),
}
ALL_LOCALES = ["en", "en-GB", "ja", "ko", "ko-KP", "und"]
WIDTHS = {"abbreviated": "3", "narrow": "4", "wide": "5", "short": "6"}
CONTEXTS = {"format": "", "stand-alone": "s"}
SEPARATOR = 0x1E


def fnv1a32(data):
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def marker_tag(name):
    return TAG + fnv1a32(name.encode()).to_bytes(4, "little")


def read_lists(cldr, marker, locale):
    """All name lists of one marker for one locale, as {attribute: [names]}."""
    package, calendar, field, order = MARKERS[marker]
    path = os.path.join(cldr, package, "main", locale, f"ca-{calendar}.json")
    data = json.load(open(path, encoding="utf-8"))["main"][locale]["dates"]["calendars"][calendar][field]
    lists = {}
    for context, suffix in CONTEXTS.items():
        for width, attribute in WIDTHS.items():
            names = data.get(context, {}).get(width)
            if names:
                lists[attribute + suffix] = [names[k] for k in order]
    return lists


def parent(locale):
    """The fallback of decision 4: remove the last subtag, then und."""
    if locale == "und":
        return None
    return locale.rsplit("-", 1)[0] if "-" in locale else "und"


def specificity(locale):
    return -1 if locale == "und" else locale.count("-")


def build(cldr, marker, locales, attributes):
    """Returns the kept keys {(locale, attribute): list} after deduplication (decision 5)."""
    raw = {loc: read_lists(cldr, marker, loc) for loc in locales}
    kept = {}
    for loc in sorted(locales, key=lambda l: (specificity(l), l)):
        for attribute, names in sorted(raw[loc].items()):
            if attributes and attribute not in attributes:
                continue
            inherited, p = None, parent(loc)
            while p is not None and inherited is None:
                inherited = kept.get((p, attribute))
                p = parent(p)
            if loc != "und" and inherited == names:
                continue
            kept[(loc, attribute)] = names
    return kept


def pack(marker, kept):
    """Packs the kept keys into the tables of decision 6."""
    pool = bytearray(marker_tag(marker))
    text_at = {}

    def text(s):
        b = s.encode("utf-8")
        assert len(b) < 256, s
        if b not in text_at:
            text_at[b] = len(pool)
            pool.extend(b)
        return (text_at[b] << 8) | len(b)

    lists, list_index = [], {}
    key_rows = []
    for (loc, attribute), names in kept.items():
        key = loc.encode() + bytes([SEPARATOR]) + attribute.encode()
        t = tuple(names)
        if t not in list_index:
            list_index[t] = len(lists)
            lists.append(t)
        key_rows.append((key, list_index[t]))
    key_rows.sort()
    keys = [text(k.decode("utf-8")) for k, _ in key_rows]
    key_lists = [i for _, i in key_rows]
    names, list_starts = [], []
    for t in lists:
        list_starts.append(len(names))
        names.extend(text(n) for n in t)
    list_starts.append(len(names))
    assert len(pool) < (1 << 24) and len(names) < (1 << 16)
    return bytes(pool), keys, key_lists, list_starts, names


def swift_array(values, width):
    return ", ".join(f"0x{v:0{width}X}" for v in values)


def write_swift(out, marker, locales, attributes, kept, tables):
    pool, keys, key_lists, list_starts, names = tables
    shown_attributes = ",".join(attributes) if attributes else "all"
    src = f"""// Generated by generator/generate.py. Do not edit.
// Marker: {marker}. CLDR {CLDR_VERSION}. Locales: {",".join(locales)}. Attributes: {shown_attributes}.
// {len(keys)} keys, {len(list_starts) - 1} lists, {len(names)} names, {len(pool)} bytes of text.
import DataMarkers
import DateNames

extension {marker}: @retroactive BakedDataMarker {{
    static let pool: InlineArray<{len(pool)}, UInt8> = [{swift_array(pool, 2)}]
    static let keys: InlineArray<{len(keys)}, UInt32> = [{swift_array(keys, 8)}]
    static let keyLists: InlineArray<{len(key_lists)}, UInt16> = [{swift_array(key_lists, 4)}]
    static let listStarts: InlineArray<{len(list_starts)}, UInt16> = [{swift_array(list_starts, 4)}]
    static let names: InlineArray<{len(names)}, UInt32> = [{swift_array(names, 8)}]

    public static func bakedLookup(_ key: DataKey) -> NameList? {{
        BakedTables.lookup(key, pool: pool.span, keys: keys.span, keyLists: keyLists.span, listStarts: listStarts.span, names: names.span)
    }}
}}
"""
    open(os.path.join(out, f"{marker}+Data.swift"), "w", encoding="utf-8").write(src)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cldr", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--markers", default=",".join(MARKERS))
    ap.add_argument("--locales", default="")
    ap.add_argument("--attributes", default="")
    args = ap.parse_args()
    markers = [m for m in args.markers.split(",") if m]
    for m in markers:
        if m not in MARKERS:
            raise SystemExit(f"Unknown marker {m!r}. Known markers: {', '.join(MARKERS)}")
    if args.locales == "all":
        # Every locale that has both calendars in this CLDR copy.
        have = lambda pkg: set(os.listdir(os.path.join(args.cldr, pkg, "main")))
        locales = sorted(have("cldr-dates-full") & have("cldr-cal-japanese-full"))
    else:
        locales = [l for l in args.locales.split(",") if l] or list(ALL_LOCALES)
    if "und" not in locales:
        locales.append("und")
    attributes = set(a for a in args.attributes.split(",") if a)
    if os.path.exists(args.out) and os.listdir(args.out):
        raise SystemExit(f"The output folder {args.out} is not empty. Use a new folder.")
    os.makedirs(args.out, exist_ok=True)
    registry, stats = {}, {}
    for marker in markers:
        kept = build(args.cldr, marker, locales, attributes)
        tables = pack(marker, kept)
        write_swift(args.out, marker, locales, sorted(attributes), kept, tables)
        pool, keys, key_lists, list_starts, names = tables
        registry[marker] = {"hash": fnv1a32(marker.encode()), "tag": marker_tag(marker).hex(" ")}
        stats[marker] = {"keys": len(keys), "lists": len(list_starts) - 1, "names": len(names), "pool_bytes": len(pool),
                         "table_bytes": len(pool) + 4 * len(keys) + 2 * len(key_lists) + 2 * len(list_starts) + 4 * len(names),
                         "kept_keys": [f"{l}/{a}" for (l, a) in sorted(kept)]}
        print(f"{marker}: {len(keys)} keys, {len(list_starts) - 1} lists, {stats[marker]['table_bytes']} bytes of tables")
    json.dump({"cldr": CLDR_VERSION, "tag": TAG.decode(), "markers": registry}, open(os.path.join(args.out, "markers.json"), "w"), indent=1)
    json.dump(stats, open(os.path.join(args.out, "stats.json"), "w"), indent=1, ensure_ascii=False)


if __name__ == "__main__":
    main()
